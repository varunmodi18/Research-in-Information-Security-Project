_REGISTRY: dict[str, ParamSet] = {}


def register(param_set: ParamSet) -> None:
    _REGISTRY[param_set.name] = param_set


def get(name: str) -> ParamSet:
    if name not in _REGISTRY:
        _bootstrap(name)
    return _REGISTRY[name]


def _bootstrap(name: str) -> None:
    table = {
        TOY: (_TOY_CURVE, _TOY_G, True),
        DEMO: (_DEMO_CURVE, _DEMO_G, False),
        SECURE: (_SECURE_CURVE, _SECURE_G, False),
    }
    if name not in table:
        raise KeyError(f"unknown parameter set {name!r}")
    curve, (gx, gy), insecure = table[name]
    register(ParamSet(name=name, curve=curve, g=_point(curve, gx, gy), insecure=insecure))
