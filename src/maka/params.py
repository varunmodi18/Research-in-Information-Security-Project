"""Frozen parameter sets (IA-07) and the p_field / r_group domain-naming discipline (IA-02).

No attribute named `p` exists anywhere in this module or elsewhere under src/ -- three
distinct objects across RP9 and ICMDS-P are written `p`, and conflating them is a live hazard
now that AM-09 has surfaced. See PLAN.md IA-02's domain-naming table:

    RP9 `p` (curve base field, "a large prime")        -> p_field
    ICMDS-P `p` (order of G1 and G2)                    -> r_group
    our subgroup order                                  -> r_group

`params.py` exposes only `p_field` and `r_group`; tests/test_hygiene.py forbids a bare `p`
binding anywhere under src/.
"""

from __future__ import annotations

from dataclasses import dataclass

from maka.curve import CurveParams, Point
from maka.field import Fp


@dataclass(frozen=True)
class ParamSet:
    name: str
    curve: CurveParams
    g: Point  # generator of the order-r_group subgroup
    insecure: bool  # `toy` is deliberately too small to offer any security margin


def _point(curve: CurveParams, x: int, y: int) -> Point:
    return Point(Fp(x, curve.p_field), Fp(y, curve.p_field), curve)


